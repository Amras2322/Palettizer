use super::{color, Adapter, FilePatch, Patched};
use crate::env::Env;
use crate::palette::Palette;
use crate::textedit::{leading_key, patch_assignments, Insert};
use anyhow::{anyhow, Result};
use indexmap::IndexMap;
use std::path::PathBuf;

/// btop — a generated theme file plus `btop.conf`.
///
/// btop themes are a flat `theme[key]="value"` file, so this adapter generates
/// the whole theme from the palette (template-driven, as the plan recommends)
/// and points `btop.conf`'s `color_theme` at it. A user's previous theme file
/// (and btop.conf) are backed up before being overwritten.
pub struct Btop;

const THEME_NAME: &str = "palettizer";

impl Adapter for Btop {
    fn name(&self) -> &'static str {
        "btop"
    }

    fn config_candidates(&self, env: &Env) -> Vec<PathBuf> {
        env.app_config("btop/btop.conf").into_iter().collect()
    }

    fn patch(&self, env: &Env, palette: &Palette) -> Result<Patched> {
        let conf = self
            .resolved_config(env)
            .ok_or_else(|| anyhow!("btop.conf not found"))?;
        let existing_conf = std::fs::read_to_string(&conf)?;

        let mut assignments: IndexMap<String, String> = IndexMap::new();
        assignments.insert("color_theme".into(), format!("\"{THEME_NAME}\""));
        let (new_conf, mut touched) = patch_assignments(
            &existing_conf,
            &assignments,
            |line| leading_key(line).map(str::to_string),
            |k, v| format!("{k} = {v}"),
            Insert::End,
        );

        let theme_path = env
            .app_config(format!("btop/themes/{THEME_NAME}.theme"))
            .ok_or_else(|| anyhow!("cannot resolve btop themes directory"))?;
        let theme = render_theme(palette);
        touched.push(format!("themes/{THEME_NAME}.theme"));

        Ok(Patched {
            files: vec![
                FilePatch {
                    path: theme_path,
                    content: theme,
                },
                FilePatch {
                    path: conf,
                    content: new_conf,
                },
            ],
            keys_touched: touched,
        })
    }
}

/// Theme keys in btop's expected order, with the canonical color each takes.
const THEME_KEYS: &[(&str, &str)] = &[
    ("main_bg", "background"),
    ("main_fg", "foreground"),
    ("title", "foreground"),
    ("hi_fg", "blue"),
    ("selected_bg", "brightBlack"),
    ("selected_fg", "foreground"),
    ("inactive_fg", "brightBlack"),
    ("proc_misc", "cyan"),
    ("cpu_box", "blue"),
    ("mem_box", "green"),
    ("net_box", "red"),
    ("proc_box", "blue"),
    ("div_line", "brightBlack"),
    ("temp_start", "green"),
    ("temp_mid", "yellow"),
    ("temp_end", "red"),
    ("cpu_start", "green"),
    ("cpu_mid", "yellow"),
    ("cpu_end", "red"),
    ("free_start", "red"),
    ("free_mid", "yellow"),
    ("free_end", "green"),
    ("cached_start", "cyan"),
    ("cached_mid", "blue"),
    ("cached_end", "magenta"),
    ("available_start", "green"),
    ("available_mid", "yellow"),
    ("available_end", "red"),
    ("used_start", "red"),
    ("used_mid", "yellow"),
    ("used_end", "green"),
    ("download_start", "cyan"),
    ("download_mid", "blue"),
    ("download_end", "magenta"),
    ("upload_start", "green"),
    ("upload_mid", "yellow"),
    ("upload_end", "red"),
];

fn render_theme(palette: &Palette) -> String {
    let mut values: IndexMap<String, String> = IndexMap::new();
    for (key, canonical) in THEME_KEYS {
        if let Some(hex) = color(palette, canonical) {
            values.insert((*key).to_string(), hex);
        }
    }
    if let Some(overrides) = palette.overrides_for("btop") {
        for (key, raw) in overrides {
            if let Some(hex) = crate::palette::normalize_hex(raw) {
                values.insert(key.clone(), hex);
            }
        }
    }
    let mut out = String::from("# Generated by palettizer - do not edit\n");
    for (key, hex) in &values {
        out.push_str(&format!("theme[{key}]=\"{hex}\"\n"));
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::adapters::testpalette::palette;

    #[test]
    fn theme_contains_core_keys() {
        let theme = render_theme(&palette());
        assert!(theme.contains("theme[main_bg]=\"#111111\""));
        assert!(theme.contains("theme[main_fg]=\"#eeeeee\""));
        assert!(theme.contains("theme[hi_fg]=\"#0000ff\""));
        assert!(theme.contains("theme[mem_box]=\"#00ff00\""));
    }

    #[test]
    fn conf_color_theme_is_replaced() {
        let conf = "color_theme = \"Default\"\nupdate_ms = 2000\n";
        let mut a: IndexMap<String, String> = IndexMap::new();
        a.insert("color_theme".into(), "\"palettizer\"".into());
        let (out, touched) = patch_assignments(
            conf,
            &a,
            |l| leading_key(l).map(str::to_string),
            |k, v| format!("{k} = {v}"),
            Insert::End,
        );
        assert!(out.contains("color_theme = \"palettizer\""));
        assert!(out.contains("update_ms = 2000"));
        assert_eq!(touched, vec!["color_theme"]);
    }
}
